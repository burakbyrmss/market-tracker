// Builds the bundled coin icons and names (ADR 0008) from the CC0 Cryptocurrency Icons set and
// scripts/coin-assets/overrides.json. The output is committed. Running it again on the same
// inputs writes identical files.
//   npm run coin-assets
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

import * as prettier from 'prettier';

const require = createRequire(import.meta.url);
const iconSet = dirname(require.resolve('cryptocurrency-icons/manifest.json'));
const { version } = JSON.parse(readFileSync(join(iconSet, 'package.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(join(iconSet, 'manifest.json'), 'utf8'));
const overrides = JSON.parse(readFileSync('scripts/coin-assets/overrides.json', 'utf8'));

const ICON_DIR = 'assets/coins';
const OUT_DIR = 'src/features/coins/generated';
// Same rule as parseAssetId in src/domain/ids.ts.
const ASSET_ID = /^[A-Z0-9]{1,20}$/;

const excluded = new Set(overrides.excluded);
const names = new Map();
const icons = [];

// The manifest lists a few tickers twice. The first entry wins, so the order is stable.
for (const { symbol, name } of manifest) {
  if (!ASSET_ID.test(symbol) || excluded.has(symbol) || names.has(symbol)) continue;
  names.set(symbol, name);
  // 64 px PNGs, drawn at 32 points: sharp on 2x screens, and cheaper than parsing SVG per row.
  const file = join(iconSet, '32@2x', 'color', `${symbol.toLowerCase()}@2x.png`);
  try {
    readFileSync(file);
    icons.push({ symbol, file });
  } catch {
    // A manifest entry without an icon keeps its name only.
  }
}
for (const [symbol, name] of Object.entries(overrides.names)) {
  if (!ASSET_ID.test(symbol)) throw new Error(`Not an asset ID in overrides.json: ${symbol}`);
  names.set(symbol, name);
}

const bySymbol = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
icons.sort((a, b) => bySymbol(a.symbol, b.symbol));

rmSync(ICON_DIR, { recursive: true, force: true });
mkdirSync(ICON_DIR, { recursive: true });
for (const { symbol, file } of icons) {
  copyFileSync(file, join(ICON_DIR, `${symbol.toLowerCase()}.png`));
}

async function write(path, source) {
  const options = await prettier.resolveConfig(path);
  writeFileSync(path, await prettier.format(source, { ...options, filepath: path }));
}

mkdirSync(OUT_DIR, { recursive: true });
const header = `// Generated by scripts/build-coin-assets.mjs from cryptocurrency-icons ${version} (CC0).\n// Do not edit. Change scripts/coin-assets/overrides.json and run npm run coin-assets.\n`;

await write(
  join(OUT_DIR, 'coin-names.json'),
  JSON.stringify(Object.fromEntries([...names].sort(([a], [b]) => bySymbol(a, b)))),
);
await write(
  join(OUT_DIR, 'coin-icons.ts'),
  `${header}import type { ImageSourcePropType } from 'react-native';\n\n` +
    icons
      .map(
        ({ symbol }) =>
          `import icon${symbol} from '../../../../${ICON_DIR}/${symbol.toLowerCase()}.png';`,
      )
      .join('\n') +
    `\n\nexport const COIN_ICONS: Readonly<Record<string, ImageSourcePropType>> = {\n` +
    icons.map(({ symbol }) => `'${symbol}': icon${symbol},`).join('\n') +
    `\n};\n`,
);

console.log(`${names.size} names, ${icons.length} icons`);
